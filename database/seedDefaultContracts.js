export async function ensureDefaultContractsAndClauses(query) {
  try {
    const existingTypes = await query('SELECT * FROM contract_types').catch(() => []);
    
    // 1. Ensure "عقد موظف جديد" exists
    let newEmpType = existingTypes.find(t => t.name_ar === 'عقد موظف جديد' || t.name_en === 'New Employee Contract');
    if (!newEmpType) {
      const res = await query(
        'INSERT INTO contract_types (name_en, name_ar, sort_order, status) VALUES (?, ?, ?, ?)',
        ['New Employee Contract', 'عقد موظف جديد', 1, 'Active']
      );
      newEmpType = { id: res.insertId, name_en: 'New Employee Contract', name_ar: 'عقد موظف جديد' };
    }

    // 2. Ensure "عقد دائمي" exists
    let permType = existingTypes.find(t => t.name_ar === 'عقد دائمي' || t.name_en === 'Permanent Contract');
    if (!permType) {
      const res = await query(
        'INSERT INTO contract_types (name_en, name_ar, sort_order, status) VALUES (?, ?, ?, ?)',
        ['Permanent Contract', 'عقد دائمي', 2, 'Active']
      );
      permType = { id: res.insertId, name_en: 'Permanent Contract', name_ar: 'عقد دائمي' };
    }

    // 3. Ensure clauses for New Employee Contract if empty
    if (newEmpType?.id) {
      const rows = await query('SELECT COUNT(*) as cnt FROM contract_clauses WHERE contract_type_id = ?', [newEmpType.id]).catch(() => [{ cnt: 0 }]);
      if (rows && rows[0] && rows[0].cnt === 0) {
        for (const c of newEmpClauses) {
          await query(
            'INSERT INTO contract_clauses (contract_type_id, clause_number, title_ar, text_ar) VALUES (?, ?, ?, ?)',
            [newEmpType.id, c.clause_number, c.title_ar, c.text_ar]
          );
        }
      }
    }

    // 4. Ensure clauses for Permanent Contract if empty
    if (permType?.id) {
      const rows = await query('SELECT COUNT(*) as cnt FROM contract_clauses WHERE contract_type_id = ?', [permType.id]).catch(() => [{ cnt: 0 }]);
      if (rows && rows[0] && rows[0].cnt === 0) {
        for (const c of permanentClauses) {
          await query(
            'INSERT INTO contract_clauses (contract_type_id, clause_number, title_ar, text_ar) VALUES (?, ?, ?, ?)',
            [permType.id, c.clause_number, c.title_ar, c.text_ar]
          );
        }
      }
    }
  } catch (err) {
    console.warn('ensureDefaultContractsAndClauses note:', err.message);
  }
}
