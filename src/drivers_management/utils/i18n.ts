export const getLang = (): 'ar' | 'en' => {
  if (typeof window !== 'undefined') {
    // Drivers do not have the sidebar language switcher, so their administrator-
    // assigned profile language is authoritative on every login and device.
    // @ts-ignore
    const portalUser = window.__PORTAL_USER__;
    if (portalUser?.role === 'driver' && (portalUser.preferred_language === 'en' || portalUser.preferred_language === 'ar')) {
      return portalUser.preferred_language;
    }
    const hrisStored = localStorage.getItem('vitas_language');
    if (hrisStored === 'en' || hrisStored === 'ar') {
      return hrisStored;
    }
    const stored = localStorage.getItem('dtms_preferred_language');
    if (stored === 'en' || stored === 'ar') {
      return stored;
    }
    // @ts-ignore
    if (window.__PORTAL_USER__ && window.__PORTAL_USER__.preferred_language === 'en') {
      return 'en';
    }
  }
  return 'ar';
};

export const t = (key: keyof typeof translations.ar): string => {
  const lang = getLang();
  return translations[lang][key] || key;
};

export const tr = (arText: string, enText: string): string => {
  return getLang() === 'en' ? enText : arText;
};

export const isCorruptedText = (value?: string | null): boolean => {
  const text = String(value || '').trim();
  if (!text) return false;
  if (/^\?+(?:[\s\-_.،]+\?+)*$/u.test(text)) return true;
  return /(?:Ã.|Â.|Ø.|Ù.|Û.){2,}/u.test(text);
};

export const readableText = (value: string | null | undefined, ...fallbacks: Array<string | null | undefined>): string => {
  for (const candidate of [value, ...fallbacks]) {
    const text = String(candidate || '').trim();
    if (text && !isCorruptedText(text)) return text;
  }
  return '';
};

export const useLanguage = () => {
  return { t, tr, lang: getLang() };
};
